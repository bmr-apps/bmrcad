// bmrcad-fn — 별무리 캐드 의 서버 함수
// 만든 3D 모델을 이 앱 스키마(bmrcad)의 projects 표에 저장·불러오기 합니다.
//
// 주소: https://psupfmarnyxontorftio.supabase.co/functions/v1/bmrcad-fn/<경로>
//   GET    /health          DB 연결·표 준비 확인
//   GET    /projects        내 모델 + 공개 모델 목록 (로그인했으면 내 것, 아니면 공개만)
//   POST   /projects        (로그인 필요) { id?, title, data, is_public } 저장/덮어쓰기
//   DELETE /projects/:id    (로그인 필요) 내 모델 지우기
//
// 표가 아직 없으면 첫 요청 때 ensureSchema 가 만들어 둡니다(마이그레이션과 같은 모양).
// 비밀값(BMRCAD_…)은 허브의 개발자 셀프서비스에서 넣습니다. 브라우저에는 공개 키만 나갑니다.
import postgres from 'npm:postgres@3.4.5';

const FN = 'bmrcad-fn';
const SCHEMA = 'bmrcad';
const PREFIX = 'BMRCAD_';
const ORIGINS = ['https://apps.bmrschool.net', 'http://localhost:5173', 'http://127.0.0.1:5173', 'http://localhost:4173', 'http://127.0.0.1:4173'];
const MAX_BODY = 2 * 1024 * 1024; // 2MB — 도형 400개짜리 모델도 넉넉합니다

const secret = (name: string) => Deno.env.get(PREFIX + name) ?? '';
const DB_URL = secret('DB_URL');
// 서버리스라 연결을 적게: 최대 2개, 20초 쉬면 닫음. 트랜잭션 풀러(6543)라 prepare 끔
const db = DB_URL ? postgres(DB_URL, { prepare: false, max: 2, idle_timeout: 20, connect_timeout: 10, onnotice: () => {} }) : null;

function cors(req: Request): Record<string, string> {
  const o = req.headers.get('Origin') ?? '';
  return {
    'Access-Control-Allow-Origin': ORIGINS.includes(o) ? o : ORIGINS[0],
    'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
    'Access-Control-Allow-Methods': 'GET, POST, DELETE, OPTIONS',
    'Access-Control-Max-Age': '600', Vary: 'Origin',
  };
}
const json = (req: Request, status: number, body: unknown) =>
  new Response(JSON.stringify(body), { status, headers: { ...cors(req), 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' } });

type User = { id: string; email: string | null } | null;
/** Authorization: Bearer <사용자 토큰> 이 있으면 Supabase Auth 에 물어 확인한다. 공개 키·잘못된 토큰이면 손님(null). */
async function getUser(req: Request): Promise<User> {
  const m = /^Bearer\s+(.+)$/i.exec(req.headers.get('Authorization') ?? '');
  const token = m?.[1] ?? '';
  if (!token || token.startsWith('sb_') || token.split('.').length !== 3) return null;
  const r = await fetch(`${Deno.env.get('SUPABASE_URL')}/auth/v1/user`, {
    headers: { apikey: Deno.env.get('SUPABASE_ANON_KEY') ?? '', Authorization: `Bearer ${token}` },
  });
  if (!r.ok) return null;
  const u = await r.json();
  return u?.id ? { id: u.id, email: u.email ?? null } : null;
}
const route = (req: Request) => {
  const p = new URL(req.url).pathname; const i = p.indexOf('/' + FN);
  return (i < 0 ? '/' : p.slice(i + FN.length + 1)).replace(/\/+$/, '') || '/';
};

// 표가 없으면 한 번만 만든다 (마이그레이션 202611150001_bmrcad_init.sql 과 같은 모양)
let schemaReady: Promise<boolean> | null = null;
function ensureSchema(sql: postgres.Sql): Promise<boolean> {
  schemaReady ??= (async () => {
    try {
      await sql`create table if not exists bmrcad.projects (
        id bigint generated by default as identity primary key,
        user_id uuid,
        author_name text,
        title text not null default '제목 없는 모델',
        data jsonb not null default '{}'::jsonb,
        is_public boolean not null default false,
        created_at timestamptz not null default now(),
        updated_at timestamptz not null default now()
      )`;
      await sql`create index if not exists projects_user_idx on bmrcad.projects (user_id, updated_at desc)`;
      return true;
    } catch (e) {
      console.error(FN, 'ensureSchema', (e as { code?: string })?.code ?? '', (e as Error)?.message ?? e);
      schemaReady = null; // 다음 요청에 다시 시도
      return false;
    }
  })();
  return schemaReady;
}

const PROJECT_COLS = `id, title, is_public, author_name, created_at, updated_at, data`;
const cleanTitle = (v: unknown) => String(v ?? '').trim().slice(0, 60) || '제목 없는 모델';

function validData(v: unknown): v is { objects: unknown[] } {
  if (!v || typeof v !== 'object') return false;
  const objects = (v as { objects?: unknown }).objects;
  return Array.isArray(objects) && objects.length <= 400;
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response(null, { status: 204, headers: cors(req) });
  const o = req.headers.get('Origin');
  if (o && !ORIGINS.includes(o)) return json(req, 403, { error: '허용되지 않은 출처입니다.' });
  const path = route(req);

  if (path === '/health') {
    if (!db) return json(req, 503, { ok: false, db: false });
    const ready = await ensureSchema(db);
    return json(req, 200, { ok: ready, db: true, schema: ready });
  }

  try {
    if (!db) return json(req, 503, { error: '서버 설정이 아직 끝나지 않았습니다 (DB 연결 정보 없음).' });
    const user = await getUser(req);

    // 목록 — 로그인했으면 내 모델과 공개 모델, 아니면 공개 모델만
    if (path === '/projects' && req.method === 'GET') {
      if (!(await ensureSchema(db))) return json(req, 503, { error: '표를 준비하지 못했습니다.', schema: false });
      const rows = user
        ? await db`select ${db.unsafe(PROJECT_COLS)} from ${db(SCHEMA)}.projects
            where user_id = ${user.id} or is_public = true order by updated_at desc limit 60`
        : await db`select ${db.unsafe(PROJECT_COLS)} from ${db(SCHEMA)}.projects
            where is_public = true order by updated_at desc limit 60`;
      return json(req, 200, { projects: rows });
    }

    // 저장 — 로그인한 사람만
    if (path === '/projects' && req.method === 'POST') {
      if (!user) return json(req, 401, { error: '로그인이 필요합니다.' });
      const text = await req.text();
      if (text.length > MAX_BODY) return json(req, 413, { error: '모델이 너무 큽니다 (2MB 까지).' });
      let body: { id?: unknown; title?: unknown; data?: unknown; is_public?: unknown };
      try { body = JSON.parse(text); } catch { return json(req, 400, { error: 'JSON 형식이 아닙니다.' }); }
      if (!validData(body.data)) return json(req, 400, { error: 'data 에 objects 배열이 있어야 합니다.' });
      if (!(await ensureSchema(db))) return json(req, 503, { error: '표를 준비하지 못했습니다.', schema: false });
      const title = cleanTitle(body.title);
      const dataJson = db.json(body.data as postgres.JSONValue);
      const isPublic = body.is_public === true;
      const authorName = (user.email ?? '').split('@')[0].slice(0, 80) || null;
      const idNum = Number(body.id);

      if (body.id != null && Number.isFinite(idNum) && idNum > 0) {
        const rows = await db`update ${db(SCHEMA)}.projects
          set title = ${title}, data = ${dataJson}, is_public = ${isPublic}, updated_at = now()
          where id = ${idNum} and user_id = ${user.id}
          returning ${db.unsafe(PROJECT_COLS)}`;
        if (!rows.length) return json(req, 404, { error: '내 모델이 아니거나 이미 지워졌습니다.' });
        return json(req, 200, { project: rows[0] });
      }
      const rows = await db`insert into ${db(SCHEMA)}.projects (user_id, author_name, title, data, is_public)
        values (${user.id}, ${authorName}, ${title}, ${dataJson}, ${isPublic})
        returning ${db.unsafe(PROJECT_COLS)}`;
      return json(req, 201, { project: rows[0] });
    }

    // 지우기 — 내 모델만
    const del = /^\/projects\/(\d+)$/.exec(path);
    if (del && req.method === 'DELETE') {
      if (!user) return json(req, 401, { error: '로그인이 필요합니다.' });
      if (!(await ensureSchema(db))) return json(req, 503, { error: '표를 준비하지 못했습니다.', schema: false });
      const rows = await db`delete from ${db(SCHEMA)}.projects
        where id = ${Number(del[1])} and user_id = ${user.id} returning id`;
      if (!rows.length) return json(req, 404, { error: '내 모델이 아니거나 이미 지워졌습니다.' });
      return json(req, 200, { ok: true, id: rows[0].id });
    }

    return json(req, 404, { error: '없는 경로입니다.' });
  } catch (e) {
    const code = (e as { code?: string })?.code;
    console.error(FN, path, code ?? '', (e as Error)?.message ?? e);
    // 42P01: 표 없음 → 마이그레이션이 아직 안 돌았을 때
    if (code === '42P01') return json(req, 503, { error: '표가 아직 없습니다. 마이그레이션을 실행해 주세요.', code });
    return json(req, 500, { error: '서버 오류가 났습니다.', code });
  }
});
