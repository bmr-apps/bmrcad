-- 별무리 캐드: 만든 3D 모델을 담는 표
--   npm run db:migrate 로 적용합니다. (서버 함수 bmrcad-fn 의 ensureSchema 와 같은 모양)
--   표는 이 앱 스키마(bmrcad) 안에만 생기고, 다른 앱·허브 표는 건드리지 않습니다.

create table if not exists projects (
  id bigint generated by default as identity primary key,
  user_id uuid,                                        -- 만든 사람 (auth.users.id, 다른 스키마라 외래키는 걸지 않음)
  author_name text,
  title text not null default '제목 없는 모델',
  data jsonb not null default '{}'::jsonb,             -- { app, version, objects: [...] }
  is_public boolean not null default false,            -- 참이면 다른 사람도 목록에서 볼 수 있음
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists projects_user_idx on projects (user_id, updated_at desc);
create index if not exists projects_public_idx on projects (updated_at desc) where is_public;

-- 브라우저(공개 키)로는 표에 직접 닿지 못하게 하고, 서버 함수(bmrcad_fn)로만 다룹니다.
-- 함수는 표 주인 역할로 접속하므로 RLS 를 지나갑니다 → 누가 무엇을 보는지는 함수 코드가 정합니다.
do $$
begin
  alter table projects enable row level security;
exception when insufficient_privilege then
  raise notice 'RLS 는 표 주인만 바꿀 수 있어 건너뜁니다 (표 권한이 이미 브라우저 역할에 없으므로 그대로 안전합니다).';
end $$;
